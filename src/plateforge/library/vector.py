"""What the ordered fragment lands in, and therefore what has to be on its ends.

A synthesised fragment is only orderable once you know what it is going into.
The vector decides three things the fragment cannot decide for itself:

  * what is already there, and so what must NOT be ordered (promoter, Kozak,
    start codon, signal peptide, the linker, the light chain, the tag)
  * where the two ligation boundaries fall, and so what the fusion sites are
  * what has to be checked (frame, internal sites, the joined reading frame
    actually translating to the protein that was designed)

This module holds vector *contexts* -- a declared list of elements on either
side of the insert -- and nothing about how the joining is done. The joining
is `library.cloning`, so a vector can be re-cut with a different strategy and
a strategy can be applied to a different vector.

The working example, `pcdna-scfv-vk-v1`: the vector already carries CMV,
Kozak, ATG, a mouse Ig-kappa secretion leader, and downstream of the insert
the (G4S)3 linker, an IGKV1-39/IGKJ1 light chain, a His6 tag and a stop. What
you order is the VH domain alone, and the finished ORF is

    ATG--leader--[VH]--(G4S)3--VL--His6--stop

Why the fusion sites are not at the VH edges
--------------------------------------------
Golden Gate overhangs have to be identical across every insert for one vector
to accept all 96. VH N-termini are not identical -- IGHV3-23 starts EVQL and
IGHV1-69 starts QVQL -- so an overhang taken from the VH itself would differ
per clone and need a different vector each time. The sites therefore sit in
the constant flanks: the last 4 nt of the leader, and the first 4 nt of the
linker. Each fragment carries those few nucleotides of vector context on
either end, which is ordinary MoClo practice and leaves the junction scarless.

Sequences here are FIXED
------------------------
A vector is a physical object. Its sequence cannot be regenerated by a codon
optimiser on each run, or two runs would design fragments for two different
plasmids. The DNA below was produced once by `codon.optimize` and is now a
constant; changing it means a new vector entry with a new name, not an edit.
"""
