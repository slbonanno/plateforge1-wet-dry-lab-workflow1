# --- the working vector: two promoters, two cassettes -----------------------
# Why this and not the T2A construct above.
#
# 2A skipping is not complete, and whatever fraction does skip translates the
# downstream ORF at a lower level than the upstream one. For IgG that is the
# wrong way round: assembly wants light chain in excess of heavy, typically
# 1.5-2:1, because free heavy chain that cannot find a partner aggregates and
# takes assembled yield down with it. HC-first T2A delivers the opposite ratio
# and offers no handle to tune it -- the ratio is a property of the peptide,
# not of anything you can change.
#
# Two independent cassettes make the ratio a design parameter instead. CAG on
# the light chain is deliberately the stronger of the two promoters.
#
# The insert does not move: the VH still sits between the heavy chain's leader
# and CH1, so the fusion sites are unchanged and fragments designed for the
# T2A vector are byte-identical to fragments designed for this one.

