@dataclass(frozen=True)
class Element:
    """One piece of the expression cassette, and whether it is ordered.

    `dna=None` means the element is in the plasmid but its sequence is not
    tracked here -- a promoter's exact sequence does not affect fragment
    design, and pretending to know it would invite someone to trust it.
    """
    name: str
    kind: str                       # promoter | kozak | start | signal |
                                    # linker | domain | tag | stop | terminator
    dna: str | None = None
    aa: str | None = None
    source: str = ""
    notes: str = ""

    @property
    def translated(self) -> bool:
        """True when this element is inside the reading frame of the ORF."""
        return self.kind in {"start", "signal", "linker", "domain", "tag"}


@dataclass(frozen=True)
class Cassette:
    """One transcription unit: a promoter, a reading frame, a terminator.

    A vector may hold more than one. That is not a detail -- it is the whole
    difference between a T2A construct, where heavy and light chain share a
    reading frame and therefore a fixed and unfavourable stoichiometry, and a
    dual-promoter construct, where each chain is transcribed on its own terms.
    """
    name: str
    elements: tuple[Element, ...] = ()
    notes: str = ""

    @property
    def carries_insert(self) -> bool:
        return any(e.kind == "insert" for e in self.elements)

    def split(self) -> tuple[tuple[Element, ...], tuple[Element, ...]]:
        """(before the insert, after it). Everything is 'before' if no insert."""
        for i, e in enumerate(self.elements):
            if e.kind == "insert":
                return self.elements[:i], self.elements[i + 1:]
        return self.elements, ()

    def coding(self, elements: tuple[Element, ...]) -> str:
        return "".join(e.dna for e in elements if e.translated and e.dna)

    def orf(self, insert_dna: str = "") -> str:
        """The finished reading frame for this cassette, stop included."""
        before, after = self.split()
        stop = next((e.dna for e in self.elements
                     if e.kind == "stop" and e.dna), "")
        return self.coding(before) + insert_dna + self.coding(after) + stop

    def protein(self, insert_dna: str = "") -> str:
        return codon.translate(self.orf(insert_dna))


def one_cassette(name: str, before: tuple[Element, ...],
                 insert: str, after: tuple[Element, ...],
                 notes: str = "") -> Cassette:
    """Build a cassette from the old upstream/[insert]/downstream shape."""
    return Cassette(name=name, notes=notes,
                    elements=before + (Element(insert, "insert"),) + after)


@dataclass(frozen=True)
class Vector:
    """A declared insertion context: what flanks the ordered fragment.

    `upstream` and `downstream` remain available and mean what they always
    meant -- what precedes and follows the insert *within its own cassette*.
    Anything in another cassette is neither, which is the point: with two
    promoters the light chain is not downstream of the heavy chain in any
    sense that a reading frame cares about.
    """
    name: str
    backbone: str
    insert: str                                  # what you order, e.g. "VH"
    cassettes: tuple[Cassette, ...] = ()
    enzyme: str = "BsaI"
    notes: str = ""

    # -- cassettes ---------------------------------------------------------
    @property
    def insert_cassette(self) -> Cassette:
        for c in self.cassettes:
            if c.carries_insert:
                return c
        raise ValueError(f"{self.name}: no cassette carries the insert")

    @property
    def upstream(self) -> tuple[Element, ...]:
        return self.insert_cassette.split()[0]

    @property
    def downstream(self) -> tuple[Element, ...]:
        return self.insert_cassette.split()[1]

    # -- the reading frames ------------------------------------------------
    def upstream_dna(self) -> str:
        c = self.insert_cassette
        return c.coding(c.split()[0])

    def downstream_dna(self) -> str:
        c = self.insert_cassette
        return c.coding(c.split()[1])

    def orf(self, insert_dna: str) -> str:
        """The reading frame the insert lands in. Others are unaffected."""
        return self.insert_cassette.orf(insert_dna)

    def protein(self, insert_dna: str) -> str:
        return codon.translate(self.orf(insert_dna))

    def orfs(self, insert_dna: str) -> dict[str, str]:
        """Every cassette's reading frame, keyed by cassette name."""
        return {c.name: c.orf(insert_dna if c.carries_insert else "")
                for c in self.cassettes}

    def proteins(self, insert_dna: str) -> dict[str, str]:
        return {name: codon.translate(orf)
                for name, orf in self.orfs(insert_dna).items()}

    # -- the boundaries ----------------------------------------------------
    def fusion_sites(self, width: int = 4) -> tuple[str, str]:
        """(5', 3') overhangs, taken from the constant flanks.

        The 5' site is the tail of whatever the insert follows and the 3' site
        the head of whatever it precedes, so both are the same in every clone.
        """
        up, down = self.upstream_dna(), self.downstream_dna()
        if len(up) < width or len(down) < width:
            raise ValueError(f"{self.name}: not enough flanking coding sequence "
                             f"for {width}-nt fusion sites")
        return up[-width:], down[:width]

    def check_fusion_sites(self, width: int = 4) -> list[str]:
        """Reasons this pair of overhangs would misbehave in one reaction."""
        five, three = self.fusion_sites(width)
        problems = []
        for site in (five, three):
            if site == codon.reverse_complement(site):
                problems.append(f"{site} is palindromic; it will self-ligate")
        if five == three:
            problems.append(f"both fusion sites are {five}; the insert could "
                            "ligate in either orientation")
        if five == codon.reverse_complement(three):
            problems.append(f"{five} and {three} are complementary; the insert "
                            "could ligate in either orientation")
        matches = sum(a == b for a, b in zip(five, three))
        if matches >= width - 1:
            problems.append(f"{five} and {three} differ at only "
                            f"{width - matches} position(s); mis-ligation is likely")
        return problems

    # -- size ---------------------------------------------------------------
    def declared_bp(self, insert_dna: str = "") -> dict[str, int]:
        """Length of every element whose sequence is actually declared.

        Elements with `dna=None` -- promoters, origins, the backbone -- are
        NOT counted, and `undeclared` says how many were skipped. A plasmid
        size that silently omitted its own promoters would be worse than no
        number at all.
        """
        out, undeclared = {}, 0
        for c in self.cassettes:
            total = 0
            for e in c.elements:
                if e.kind == "insert":
                    total += len(insert_dna)
                elif e.dna:
                    total += len(e.dna)
                else:
                    undeclared += 1
            out[c.name] = total
        out["_total_declared"] = sum(v for k, v in out.items()
                                     if not k.startswith("_"))
        out["_undeclared_elements"] = undeclared
        return out

    # -- the record --------------------------------------------------------
    def as_dict(self) -> dict:
        five, three = self.fusion_sites()
        return {
            "name": self.name,
            "backbone": self.backbone,
            "insert": self.insert,
            "enzyme": self.enzyme,
            "fusion_site_5p": five,
            "fusion_site_3p": three,
            "cassettes": [
                {"name": c.name,
                 "carries_insert": c.carries_insert,
                 "elements": [e.name for e in c.elements],
                 "notes": c.notes}
                for c in self.cassettes
            ],
            "upstream": [e.name for e in self.upstream],
            "downstream": [e.name for e in self.downstream],
            "upstream_coding_bp": len(self.upstream_dna()),
            "downstream_coding_bp": len(self.downstream_dna()),
            "declared_bp": self.declared_bp(),
            "notes": self.notes,
        }

    def describe(self) -> str:
        five, three = self.fusion_sites()
        lines = [f"{self.name} ({self.backbone})"]
        for c in self.cassettes:
            parts = " - ".join(f"[{e.name}]" if e.kind == "insert" else e.name
                               for e in c.elements)
            lines.append(f"  {c.name}: {parts}")
        lines.append(f"  {self.enzyme} fusion sites: 5' {five} / 3' {three}")
        return "\n".join(lines)


def register(vec: Vector) -> Vector:
    VECTORS.add(vec.name, vec, backbone=vec.backbone, enzyme=vec.enzyme)
    return vec


def get(name: str) -> Vector:
    return VECTORS.get(name)


